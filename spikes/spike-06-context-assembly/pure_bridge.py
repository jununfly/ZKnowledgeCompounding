"""Process-only public aliases for recording context.py's private pure helper.

Scope
-----
This file lives in the spike-06 research directory (a unit `rust-anything analyze`
already knows) because the tool refuses to bridge source files outside a known
unit, and it only exports public functions. The two aliases below delegate
verbatim to `zkc.context`; no behavior is reimplemented here. The Python original
is therefore the sole recording oracle for the Rust port.

Why the Rust port is longer than the shim
----------------------------------------
- `_clean_title` relies on Python `str.splitlines()`, `str.strip()` and slicing;
  Rust needs explicit handling of Python's wider line-break set and char counts.
- `fallback_name` relies on `re.findall`, `collections.Counter` and a composite
  sort; Rust needs an explicit scanner plus a BTreeMap tie-break.
- Errors are not a concern for these two helpers (0 thrown cases in 131), but
  Python's Unicode lowercasing can expand one code point into several; the Rust
  scanner operates on `to_lowercase()` output to preserve that behavior.

Recording contract
------------------
Cases are generated by `rust-anything record --count 40` plus
`tmp/context-inputs.jsonl`. The targeted families are:

1. `clean_title`: empty / whitespace-only input, first non-empty line after a
   leading blank line, ASCII quotes stripped from both ends, Chinese curly
   quotes deliberately preserved, and the 32-character truncation boundary.
2. `fallback_name`: no members, all stop characters, ASCII single-character
   noise versus CJK single characters, frequency ties resolved by token order,
   `İ` lowercasing to `i` plus a combining dot (ASCII singleton dropped), and
   negative / zero `n_members` in the rendered label.

Nothing in this shim is part of production code. The real source of truth stays
`src/zkc/context.py`; deleting this file only breaks re-recording, not the app.
"""
from zkc.context import _clean_title, fallback_name as _fallback_name


def clean_title(raw: str) -> str:
    """Alias of `zkc.context._clean_title`."""
    return _clean_title(raw)


def fallback_name(member_texts: list[str], n_members: int) -> str:
    """Alias of `zkc.context.fallback_name`."""
    return _fallback_name(member_texts, n_members)
